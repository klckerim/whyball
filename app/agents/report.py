"""docs/AGENT_RUN.md from docs/AGENT_RUN.json (no model call): python -m app.agents.report [--run FILE] [--out FILE]."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_RUN = REPO_ROOT / "docs" / "AGENT_RUN.json"
DEFAULT_OUT = REPO_ROOT / "docs" / "AGENT_RUN.md"


def _cell(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _card(match_id: str, m: dict[str, Any]) -> dict[str, Any]:
    t = m["trace"]
    analyst = next(s for s in t if s["step"] == "analyst")["output"] if any(s["step"] == "analyst" for s in t) else None
    fallback = any(s["step"] == "analyst_fallback" for s in t)
    rejects = [(s["attempt"], i) for s in t if s["step"] == "verify" and s["output"].get("verdict") == "reject"
               for i in s["output"]["issues"]]
    guard = [(s["attempt"], s["output"]["codes"]) for s in t if s["step"] == "guard" and not s["output"]["ok"]]
    tokens = [s["tokens"] for s in t if s["tokens"]["in"] is not None]
    return {
        "match": match_id, "id": m["id"], "type": m["type"], "source": m["source"], "v": m["verification"],
        "analyst": analyst, "analyst_fallback": fallback, "rejects": rejects, "guard_rejects": guard,
        "verifier_errors": [s for s in t if s["step"] == "verifier_error"],
        "seconds": max((s["started_ms"] + s["duration_ms"] for s in t), default=0) / 1000,
        "tin": sum(x["in"] or 0 for x in tokens), "tout": sum(x["out"] or 0 for x in tokens), "trace": t,
    }


def render(data: dict[str, Any], run_name: str = "docs/AGENT_RUN.json") -> str:
    meta, run = data["meta"], data["runs"][-1]
    cards = [_card(mt["match_id"], m) for mt in run["matches"] for m in mt["moments"]]
    by_agent: dict[str, list[int]] = {}
    for c in cards:
        for s in c["trace"]:
            if s["tokens"]["in"] is not None:
                x = by_agent.setdefault(s["agent"], [0, 0, 0])
                x[0] += s["tokens"]["in"] or 0
                x[1] += s["tokens"]["out"] or 0
                x[2] += 1
    lines = [
        "# Agent run", "",
        f"Generated by `python -m app.agents.report` from `{run_name}`. Do not edit by hand. No model is called.", "",
        f"- Run `{meta['prompt_version']}@{run['started_at']}`; analyst `{meta['analyst_version']}`, verifier "
        f"`{meta['verifier_version']}`; flags {meta['flags']}; moments `{meta['moments']}`; model `{meta['model']}`.",
        f"- {len(cards)} cards, {meta['calls']} model calls, {meta['tokens']['in']:,} tokens in / {meta['tokens']['out']:,} out "
        f"({meta['tokens']['reasoning']:,} reasoning), {meta['wall_seconds']} s wall time. Limits: {meta['max_attempts']} attempts, "
        f"timeouts {meta['timeouts_s']}, budget {meta['max_calls_per_run']} calls.", "",
        "## Tokens by agent", "", "| Agent | Calls | In | Out |", "|---|---:|---:|---:|",
    ]
    lines += [f"| {a} | {n} | {i:,} | {o:,} |" for a, (i, o, n) in sorted(by_agent.items())]
    src = {s: sum(c["source"] == s for c in cards) for s in ("llm", "template_fallback")}
    guard_only = sum(c["v"]["label_source"] == "guard_only" for c in cards)
    ver: dict[str, int] = {}
    for c in cards:
        ver[c["v"]["verifier"]] = ver.get(c["v"]["verifier"], 0) + 1
    lines += [
        "", "## Outcome", "",
        f"- Sources: {src}; guard-only {guard_only}; verifier status {ver}.",
        f"- Analyst fallbacks: {sum(c['analyst_fallback'] for c in cards)}; Guard rejections: "
        f"{sum(len(c['guard_rejects']) for c in cards)}; Verifier rejections: {sum(len(c['rejects']) for c in cards)}; "
        f"Verifier errors: {sum(len(c['verifier_errors']) for c in cards)}.", "",
        "## Cards", "",
        "| Match | Moment | Type | Attempts | Source | Verifier | Analyst (menu → kept; expanded) | Rejections | Time | Tokens in/out |",
        "|---|---|---|---:|---|---|---|---|---:|---:|",
    ]
    for c in cards:
        a = c["analyst"]
        if c["analyst_fallback"]:
            an = f"fallback: {a['error']}" + (f" (`{a['token']}`)" if a.get("token") else "") if a else "fallback"
        elif a:
            an = f"{a['menu_claims']} → {len(a['effective'])}" + (f"; {', '.join(a['expanded_clause_ids'])}" if a.get("expanded_clause_ids") else "")
        else:
            an = "off"
        rej = [f"Verifier {i['code']} «{i['span']}»" + (" (span not in text)" if i.get("unlocated_span") else "")
               for _, i in c["rejects"]] + [f"Guard {', '.join(codes)}" for _, codes in c["guard_rejects"]]
        lines.append(
            f"| {c['match']} | {c['id'].split('-')[-1]} | {c['type']} | {c['v']['attempts']} | {c['source']} | {c['v']['verifier']} | "
            f"{_cell(an)} | {_cell('; '.join(rej) or '—')} | {c['seconds']:.1f} s | {c['tin']:,} / {c['tout']:,} |")
    lines += ["", "## Texts", "", "| Card | Text |", "|---|---|"]
    for mt in run["matches"]:
        lines += [f"| `{m['id']}` | {_cell(m['text'])} |" for m in mt["moments"]]
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Render docs/AGENT_RUN.md")
    ap.add_argument("--run", type=Path, default=DEFAULT_RUN)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render(json.loads(args.run.read_text(encoding="utf-8")), run_name=f"docs/{args.run.name}")
    if args.check:
        return 0 if args.out.exists() and args.out.read_text(encoding="utf-8") == text else 1
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
